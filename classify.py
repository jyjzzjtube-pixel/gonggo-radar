def _norm(s):
    return re.sub(r"\s+", "", s or "")


def detect_region(title, region_hint="", agency=""):
    """(시도, 시군구) 추정"""
    t = _norm(title) + _norm(region_hint)
    # 1) region_hint(LH 지역 컬럼) 우선
    if region_hint:
        for full, short in [(v, k) for k, v in SIDO_ALIAS.items()]:
            pass
        for short in ["서울","부산","대구","인천","광주","대전","울산","세종","경기","강원",
                      "충북","충남","전북","전남","경북","경남","제주"]:
            if short in region_hint:
                sido = short
                gu = _match_gu(t, sido)
                return sido, gu
    # 2) 제목에서 시도명
    for short in ["서울","부산","대구","인천","광주","대전","울산","세종","경기","강원",
                  "충북","충남","전북","전남","경북","경남","제주"]:
        if short in t:
            return short, _match_gu(t, short)
    # 3) 시군구 역추적
    for sido, gus in SIGUNGU.items():
        for gu in gus:
            if len(gu) >= 2 and gu in t:
                return sido, gu
    # 4) 기관 기본값
    if agency == "SH":
        return "서울", _match_gu(t, "서울")
    if agency == "GH":
        return "경기", _match_gu(t, "경기")
    return "전국", ""


def _match_gu(t, sido):
    for gu in SIGUNGU.get(sido, []):
        if len(gu) >= 2 and gu in t:
            return gu
    return ""


def detect_deal(title, category=""):
    """거래유형: 임대(전세) / 임대(월세) / 매매 / 상가·업무 / 토지"""
    t = _norm(title) + _norm(category)
    # 1) 임대 키워드가 명시되면 최우선 (임대상가는 아래 BIZ에서 다시 분기)
    is_house_lease = any(k in t for k in LEASE_JEONSE + LEASE_MONTHLY)
    # 2) 토지/용지가 명시되면 토지 (주차장용지 등이 BIZ로 새는 것 방지)
    if any(k in t for k in ["용지", "택지", "대토", "토지공급", "단독주택용지", "공동주택용지"]):
        return "토지"
    if any(k in t for k in BIZ):
        return "상가·업무"
    if any(k in t for k in LAND) and not is_house_lease:
        return "토지"
    if any(k in t for k in LEASE_JEONSE):
        return "임대(전세)"
    if any(k in t for k in LEASE_MONTHLY):
        return "임대(월세)"
    if "임대" in t:
        return "임대(월세)"
    # 3) 입주자모집 계열은 주택 임대로 간주 (분양 키워드가 없을 때)
    if any(k in t for k in ["입주자모집", "예비입주자", "잔여세대", "입주자를모집", "추가모집", "수시모집"]):
        return "매매(분양·매각)" if ("분양" in t and "임대" not in t) else "임대(월세)"
    if any(k in t for k in SALE):
        return "매매(분양·매각)"
    return "기타"


def detect_house_type(title, category=""):
    t = _norm(title) + _norm(category)
    hits = [h for h in HOUSE_TYPES if h in t]
    if hits:
        return max(hits, key=len)
    return category or "기타"


def detect_quals(title):
    t = _norm(title)
    out = []
    for label, keys in QUALS.items():
        if any(k in t for k in keys):
            out.append(label)
    return out or ["일반"]


def detect_kind(title, category=""):
    """공고 성격: 모집공고 / 결과발표 / 정정 / 안내"""
    t = _norm(title)
    if any(k in t for k in ["당첨자","선정결과","결과발표","합격자","서류심사대상자","발표","명단",
                            "청약경쟁률","경쟁률","적격자","선정자","계약안내","계약체결","동호배정",
                            "소유권이전","사용검사","입주안내","잔금","취소세대안내",
                            "심사결과","심사 결과","재계약","확인증","경쟁률"]):
        return "결과발표"
    if any(k in t for k in ["정정","변경","연기","취소","수정공고"]):
        return "정정·변경"
    if any(k in t for k in ["모집","공급","공고","입찰","공모","매각","분양"]):
        return "모집공고"
    return "안내"
